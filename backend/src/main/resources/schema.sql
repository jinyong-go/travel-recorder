-- travel-recorder 스키마 (PostgreSQL)
--
-- 엔티티(com.yong.travel.*.domain)로부터 Hibernate 가 생성하는 DDL 을 기준으로 작성했다.
-- 컬럼 타입/이름을 바꾸면 `ddl-auto: validate` 가 실패하므로 엔티티와 함께 수정해야 한다.
--
-- - 재실행해도 안전하도록 모든 DDL 은 IF NOT EXISTS 를 사용하고,
--   외래키는 ALTER TABLE 대신 CREATE TABLE 안에 인라인으로 선언한다.
-- - 따라서 테이블은 참조 순서(users → tags → places → 나머지)대로 정의한다.
-- - H2 는 MODE=PostgreSQL 로 기동하므로 local 프로파일에서도 이 스크립트를 그대로 쓴다.
-- - places / reviews 는 soft delete 를 쓴다. deleted_at 이 NULL 인 행만 살아 있는 행이며,
--   엔티티의 @SQLRestriction("deleted_at is null") 이 조회에서 자동으로 걸러 낸다.
--   별도의 is_deleted / delete_yn 플래그는 두지 않는다 (deleted_at 과 어긋날 여지만 생긴다).

-- 사용자 (네이버 OAuth2 로그인)
CREATE TABLE IF NOT EXISTS users
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    provider          VARCHAR(255)                NOT NULL,
    provider_id       VARCHAR(255)                NOT NULL,
    email             VARCHAR(255)                NOT NULL,
    name              VARCHAR(255)                NOT NULL,
    profile_image_url VARCHAR(255),
    created_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_users_provider UNIQUE (provider, provider_id)
);

-- 태그 (여행지에 다중 부착되는 자유 키워드)
CREATE TABLE IF NOT EXISTS tags
(
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(255) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_tags_name UNIQUE (name)
);

-- 여행지
CREATE TABLE IF NOT EXISTS places
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    owner_id      BIGINT                      NOT NULL,
    name          VARCHAR(255)                NOT NULL,
    category      VARCHAR(255)                NOT NULL,
    address       VARCHAR(255)                NOT NULL,
    road_address  VARCHAR(255),
    external_link VARCHAR(255),
    latitude      DOUBLE PRECISION            NOT NULL,
    longitude     DOUBLE PRECISION            NOT NULL,
    memo          VARCHAR(1000),
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    deleted_at    TIMESTAMP(6) WITH TIME ZONE,
    PRIMARY KEY (id),
    CONSTRAINT ck_places_category CHECK (category IN ('SIGHT', 'SHOPPING', 'FOOD')),
    CONSTRAINT fk_places_owner FOREIGN KEY (owner_id) REFERENCES users (id)
);

-- 여행지 ↔ 태그 조인 테이블
CREATE TABLE IF NOT EXISTS place_tags
(
    place_id BIGINT NOT NULL,
    tag_id   BIGINT NOT NULL,
    PRIMARY KEY (place_id, tag_id),
    CONSTRAINT fk_place_tags_place FOREIGN KEY (place_id) REFERENCES places (id),
    CONSTRAINT fk_place_tags_tag FOREIGN KEY (tag_id) REFERENCES tags (id)
);

-- 리뷰 (별점 + 코멘트, 사용자당 여행지 1건)
-- 별점과 코멘트는 한 행에 함께 저장한다. 별점 없는 코멘트는 존재할 수 없고,
-- 코멘트 없이 별점만 남기는 것은 허용하므로 content 만 NULL 을 받는다.
-- score 는 0.5 ~ 5.0 을 0.5 단위로만 받는다. 허용 값을 CHECK 로 나열해 두면
-- 애플리케이션 검증(ReviewRequest)이 우회되더라도 DB 가 마지막으로 막아 준다.
CREATE TABLE IF NOT EXISTS reviews
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    place_id   BIGINT                      NOT NULL,
    user_id    BIGINT                      NOT NULL,
    score      DOUBLE PRECISION            NOT NULL,
    content    VARCHAR(1000),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    deleted_at TIMESTAMP(6) WITH TIME ZONE,
    PRIMARY KEY (id),
    -- soft delete 후에도 행이 남으므로 유니크 제약은 삭제 여부와 무관하게 유지된다.
    -- 재등록(upsert)은 새 행을 만들지 않고 삭제된 행의 deleted_at 을 NULL 로 되돌린다.
    CONSTRAINT ck_reviews_score CHECK (score IN (0.5, 1, 1.5, 2, 2.5, 3, 3.5, 4, 4.5, 5)),
    CONSTRAINT uk_reviews_place_user UNIQUE (place_id, user_id),
    CONSTRAINT fk_reviews_place FOREIGN KEY (place_id) REFERENCES places (id),
    CONSTRAINT fk_reviews_user FOREIGN KEY (user_id) REFERENCES users (id)
);

-- 사진 (파일 본체는 app.storage 설정 위치에 저장하고 여기에는 메타데이터만 둔다)
CREATE TABLE IF NOT EXISTS photos
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY,
    place_id           BIGINT                      NOT NULL,
    uploader_id        BIGINT                      NOT NULL,
    storage_key        VARCHAR(255)                NOT NULL,
    original_file_name VARCHAR(255)                NOT NULL,
    content_type       VARCHAR(255)                NOT NULL,
    file_size_bytes    BIGINT                      NOT NULL,
    created_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_photos_place FOREIGN KEY (place_id) REFERENCES places (id),
    CONSTRAINT fk_photos_uploader FOREIGN KEY (uploader_id) REFERENCES users (id)
);

-- 인덱스
-- PostgreSQL 은 외래키에 인덱스를 자동 생성하지 않으므로, 조회·삭제 시 사용되는 FK 컬럼에 직접 만든다.
CREATE INDEX IF NOT EXISTS idx_places_owner ON places (owner_id, deleted_at);
CREATE INDEX IF NOT EXISTS idx_places_category ON places (category);
CREATE INDEX IF NOT EXISTS idx_places_created_at ON places (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_place_tags_tag ON place_tags (tag_id);
-- soft delete 대상 테이블은 조회 시 deleted_at 조건이 항상 붙으므로 복합 인덱스로 만든다.
-- (PostgreSQL 의 부분 인덱스가 더 좋지만 H2 가 지원하지 않아 local 과 스크립트를 공유하지 못한다.)
CREATE INDEX IF NOT EXISTS idx_reviews_place ON reviews (place_id, deleted_at);
CREATE INDEX IF NOT EXISTS idx_photos_place ON photos (place_id);
CREATE INDEX IF NOT EXISTS idx_photos_uploader ON photos (uploader_id);
