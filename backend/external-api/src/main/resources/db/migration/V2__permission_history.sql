-- 권한 변경 이력. 권한 판정은 이 테이블들을 읽지 않는다 — 판정은 trips·trip_shares·group_member 의
-- 현재 값으로만 하고, 여기에는 바뀐 사실만 남긴다.

-- 여행 공개 범위가 바뀐 뒤의 상태. append-only 이며 지우지 않는다.
-- 변경 전 값을 두지 않는다 — 같은 여행의 직전 행이 답한다.
-- group_ids 는 그룹이 지워져도 남아야 해 외래키를 걸 수 없다. 한 행이 한 시점의 상태 전체이고
-- 그룹 id 하나로 찾는 조회가 없어 자식 테이블 대신 배열로 둔다. 오름차순으로 저장한다.
-- 조회 경로가 아직 없어 인덱스를 두지 않는다.
CREATE TABLE trip_visibility_history
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    trip_id    BIGINT                      NOT NULL,
    visibility VARCHAR(20)                 NOT NULL,
    group_ids  BIGINT[]                    NOT NULL,
    cause      VARCHAR(20)                 NOT NULL,
    changed_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_trip_visibility_history_trip FOREIGN KEY (trip_id) REFERENCES trips (id)
);

-- 멤버가 되거나 멤버가 아니게 된 기록. append-only 이며 지우지 않는다.
-- group_id 에 외래키를 걸지 않는 이유는 invite_history 와 같다. 그룹명은 사건 시점의 스냅샷이다.
CREATE TABLE group_member_history
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    group_id    BIGINT                      NOT NULL,
    group_name  VARCHAR(30)                 NOT NULL,
    user_id     BIGINT                      NOT NULL,
    event       VARCHAR(20)                 NOT NULL,
    occurred_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_group_member_history_user FOREIGN KEY (user_id) REFERENCES users (id)
);
